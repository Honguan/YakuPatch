"""Regenerate requirements.lock: the dependencies of pyproject.toml resolved for the Python 3.12 / win_amd64
runtime the release ships, pinned with SHA-256 hashes. Usage: python scripts/lock.py"""
import json
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    deps = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["dependencies"]
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--quiet", "--ignore-installed",
                        "--report", str(report), "--python-version", "3.12", "--platform", "win_amd64",
                        "--only-binary=:all:", "--target", str(Path(tmp) / "t"), *deps, "pip"], check=True)
        items = json.loads(report.read_text(encoding="utf-8"))["install"]
    lines = ["# Generated by scripts/lock.py for the Python 3.12 win_amd64 runtime. Do not edit by hand."]
    for item in sorted(items, key=lambda i: i["metadata"]["name"].lower()):
        sha = item["download_info"]["archive_info"]["hashes"]["sha256"]
        lines.append(f"{item['metadata']['name']}=={item['metadata']['version']} --hash=sha256:{sha}")
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(items)} packages")


if __name__ == "__main__":
    main()
